function ContactIcons({ className = "" }: { className?: string }) {
  const rootRef = useRef<HTMLUListElement>(null);

  useEffect(() => {
    const root = rootRef.current;
    if (!root) return;
    const cleanups = Array.from(
      root.querySelectorAll<HTMLElement>(".tile")
    ).map(attachTilePress);
    return () => cleanups.forEach((fn) => fn());
  }, []);

  return (
    <ul className={`tiles ${className}`.trim()} ref={rootRef}>
      {links.map((l) => (
        <li key={l.href}>
          <a
            className="tile tile--gear"
            href={l.href}
            aria-label={l.label}
            {...(l.external ? { target: "_blank", rel: "noreferrer" } : {})}
          >
            <svg
              className="tile-gear"
              viewBox="0 0 100 100"
              aria-hidden="true"
              focusable="false"
            >
              <path className="tile-gear-body" d={GEAR_PATH} />
            </svg>
            <svg
              className="tile-glyph"
              viewBox={l.viewBox}
              aria-hidden="true"
              focusable="false"
            >
              {l.paths.map((d, i) => (
                <path key={i} fill="currentColor" d={d} />
              ))}
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}

export default ContactIcons;
